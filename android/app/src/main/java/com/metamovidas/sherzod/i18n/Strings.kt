enum class Lang(val id: String, val native: String) {
    ES("es", "ES"),
    FR("fr", "FR"),
    EN("en", "EN"),
    RU("ru", "RU");

    companion object {
        fun fromId(id: String?): Lang = entries.find { it.id == id } ?: EN
        fun fromSystem(tag: String): Lang = when (tag.lowercase().take(2)) {
            "es" -> ES
            "fr" -> FR
            "ru" -> RU
            else -> EN
        }
    }
}

